"""Generate complete Unicode 16 normalization data using official CPython 3.14."""

import argparse
from pathlib import Path
import sys
import unicodedata


ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "py2fastrust/runtime/normalization_tables.rs"


def generate():
    if sys.version_info[:2] != (3, 14) or unicodedata.unidata_version != "16.0.0":
        raise SystemExit("Generate normalization tables with CPython 3.14 / Unicode 16.0.0")
    decompositions, classes, compositions = [], [], []
    for codepoint in range(sys.maxunicode + 1):
        char = chr(codepoint)
        normalized = unicodedata.normalize("NFKD", char)
        # Hangul has algorithmic decomposition/composition (Unicode chapter 3).
        if normalized != char and not 0xAC00 <= codepoint <= 0xD7A3:
            decompositions.append((codepoint, tuple(map(ord, normalized))))
        combining = unicodedata.combining(char)
        if combining:
            classes.append((codepoint, combining))
        decomposition = unicodedata.decomposition(char)
        if decomposition and not decomposition.startswith("<"):
            points = tuple(int(piece, 16) for piece in decomposition.split())
            if len(points) == 2 and unicodedata.normalize("NFC", "".join(map(chr, points))) == char:
                compositions.append((points[0], points[1], codepoint))
    lines = ["// Generated by tools/generate_normalization.py; do not edit.",
             "// Unicode 16.0.0 data; Unicode License V3, see stdlib/UNICODE_LICENSE.txt.",
             "const NORMALIZE_DECOMPOSITIONS: &[(u32,&[u32])] = &["]
    lines.extend(f"(0x{point:x},&[" + ",".join(f"0x{x:x}" for x in expansion) + "]),"
                 for point, expansion in decompositions)
    lines.extend(["];", "const NORMALIZE_COMBINING: &[(u32,u8)] = &["])
    lines.extend(f"(0x{point:x},{combining})," for point, combining in classes)
    lines.extend(["];", "const NORMALIZE_COMPOSITIONS: &[((u32,u32),u32)] = &["])
    lines.extend(f"((0x{a:x},0x{b:x}),0x{result:x})," for a, b, result in sorted(compositions))
    lines.extend(["];", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    source = generate()
    if options.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            parser.exit(1, f"stale normalization tables: {TARGET}\n")
    else:
        TARGET.write_text(source)


if __name__ == "__main__":
    main()
