"""Generate Unicode 16 single-character names for Python literal escapes."""

import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import re
import sys
import unicodedata


ROOT = Path(__file__).resolve().parents[1]
ALIASES = ROOT / "py2fastrust/unicode/NameAliases-16.0.0.txt"
ALIAS_SHA256 = "bc5e89e5a6f2cf21b1d3976af13432bab3f0b406907d7c7ba9c0f4faf3fc5b44"
TARGET = ROOT / "py2fastrust/runtime/unicode_names_tables.rs"


def read_aliases():
    data = ALIASES.read_bytes()
    if hashlib.sha256(data).hexdigest() != ALIAS_SHA256:
        raise ValueError("Unicode 16 NameAliases source checksum mismatch")
    aliases = {}
    for line in data.decode("utf-8").splitlines():
        fields = line.split("#", 1)[0].strip().split(";")
        if len(fields) == 1:
            continue
        point, name, kind = fields
        point = int(point, 16)
        if unicodedata.lookup(name) != chr(point):
            raise ValueError(f"CPython alias mismatch: {name}")
        if kind not in {"correction", "control", "alternate", "figment", "abbreviation"}:
            raise ValueError(f"Unknown alias category: {kind}")
        aliases[name] = point
    if len(aliases) != 477:
        raise ValueError("Incomplete Unicode 16 name aliases")
    return aliases


def contiguous_ranges(points):
    result = []
    for point in points:
        if result and point == result[-1][1] + 1:
            result[-1] = (result[-1][0], point)
        else:
            result.append((point, point))
    return result


def generate():
    if sys.implementation.name != "cpython" or sys.version_info[:2] != (3, 14) or unicodedata.unidata_version != "16.0.0":
        raise ValueError("Generate Unicode names with CPython 3.14 / Unicode 16.0.0")
    ordinary = read_aliases()
    families = defaultdict(list)
    for point in range(sys.maxunicode + 1):
        name = unicodedata.name(chr(point), "")
        if not name or 0xAC00 <= point <= 0xD7A3:
            continue
        match = re.fullmatch(r"(.+)-([0-9A-F]{4,6})", name)
        if match and int(match[2], 16) == point:
            families[match[1]].append(point)
        else:
            ordinary[name] = point
    # CPython accepts these algorithmic lookup names despite name(chr) being
    # absent. Probe the entire scalar space instead of assuming block bounds.
    tangut = []
    for point in range(sys.maxunicode + 1):
        try:
            value = unicodedata.lookup(f"TANGUT IDEOGRAPH-{point:X}")
        except KeyError:
            continue
        if value != chr(point):
            raise ValueError("Unexpected Tangut lookup mapping")
        tangut.append(point)
    families["TANGUT IDEOGRAPH"] = tangut
    lines = [
        "// Generated by tools/generate_unicode_names.py; do not edit.",
        "// CPython 3.14 / Unicode 16.0.0; Unicode License V3.",
        "// NameAliases source: unicode/NameAliases-16.0.0.txt (477 aliases).",
        f"// NameAliases SHA-256: {ALIAS_SHA256}",
        "const UNICODE_CHARACTER_NAMES: &[(&str,u32)] = &[",
    ]
    lines.extend(f"({json.dumps(name)},0x{point:x})," for name, point in sorted(ordinary.items()))
    lines.extend(["];", "const UNICODE_ALGORITHMIC_NAMES: &[(&str,&[(u32,u32)])] = &["])
    for prefix, points in sorted(families.items()):
        ranges = ",".join(f"(0x{first:x},0x{last:x})" for first, last in contiguous_ranges(points))
        lines.append(f"({json.dumps(prefix)},&[{ranges}]),")
    lines.extend(["];", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    try:
        data = generate()
    except ValueError as error:
        parser.exit(1, f"{error}\n")
    if options.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != data:
            parser.exit(1, f"stale Unicode name tables: {TARGET}\n")
    else:
        TARGET.write_text(data, encoding="utf-8")


if __name__ == "__main__":
    main()
