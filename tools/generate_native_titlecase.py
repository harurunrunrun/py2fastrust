#!/usr/bin/env python3
"""Generate the small titlecase property from pinned CPython Unicode 16 data."""
import argparse
from pathlib import Path
import sys
import unicodedata

TARGET=Path(__file__).resolve().parents[1]/"py2fastrust/runtime/native_titlecase_16.rs"


def generate():
    if sys.implementation.name!="cpython" or sys.version_info[:2]!=(3,14) or unicodedata.unidata_version!="16.0.0":
        raise SystemExit("Generate with CPython 3.14 and Unicode 16.0.0")
    ranges=[];start=last=None
    for codepoint in range(sys.maxunicode+1):
        if unicodedata.category(chr(codepoint))=="Lt":
            if start is None:start=codepoint
            last=codepoint
        elif start is not None:ranges.append((start,last));start=last=None
    if start is not None:ranges.append((start,last))
    lines=['// Unicode 16.0.0 General_Category=Lt, generated by tools/generate_native_titlecase.py.',
           '// Source: https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt',
           '// Unicode data license: ../stdlib/UNICODE_LICENSE.txt',
           'const NATIVE_PRED_TABLE_TITLE: &[(u32,u32)] = &[']
    lines += [f'    (0x{first:x},0x{last:x}),' for first,last in ranges]
    return '\n'.join(lines+['];',''])


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');options=parser.parse_args()
    result=generate()
    if options.check:
        if TARGET.read_text()!=result:raise SystemExit('Titlecase data needs regeneration')
    else:TARGET.write_text(result)


if __name__=='__main__':main()
