"""Render executable IR and self-contained Rust runtime sources."""

import math
from importlib.resources import files

from .ir import Program, SourceLocation


def string(value: str) -> str:
    output = ['"']
    for char in value:
        if char == '"':
            output.append('\\"')
        elif char == "\\":
            output.append("\\\\")
        elif char == "\n":
            output.append("\\n")
        elif char == "\r":
            output.append("\\r")
        elif char == "\t":
            output.append("\\t")
        elif ord(char) < 32 or ord(char) == 127:
            output.append(f"\\u{{{ord(char):x}}}")
        else:
            output.append(char)
    output.append('".to_string()')
    return "".join(output)


def strings(values):
    return "vec![" + ",".join(string(value) for value in values) + "]"


def optional(value):
    return "None" if value is None else f"Some({string(value)})"


def float_literal(value):
    return ("f64::NAN" if math.isnan(value) else
            "f64::INFINITY" if value == math.inf else
            "f64::NEG_INFINITY" if value == -math.inf else repr(value) + "_f64")


def constant(value):
    if value is None:
        return "Const::None"
    if isinstance(value, bool):
        return f"Const::Bool({str(value).lower()})"
    if isinstance(value, int):
        return f"Const::Int({string(str(value))})"
    if isinstance(value, float):
        return f"Const::Float({float_literal(value)})"
    if isinstance(value, complex):
        return f"Const::Complex({float_literal(value.real)},{float_literal(value.imag)})"
    if isinstance(value, str):
        return f"Const::Str({string(value)})"
    if isinstance(value, bytes):
        return "Const::Bytes(vec![" + ",".join(map(str, value)) + "])"
    raise TypeError(f"unsupported IR constant {type(value)}")


def pattern(value):
    kind, args = value.kind, value.args
    patterns = lambda items: "vec![" + ",".join(pattern(item) for item in items) + "]"
    if kind == "Literal":
        body = constant(args[0])
    elif kind == "ComplexNumber":
        return f"MatchPattern::ComplexNumber {{ real:{constant(args[0])},imag:{float_literal(args[1])} }}"
    elif kind == "ValuePath":
        body = strings(args[0])
    elif kind in {"Sequence", "Or"}:
        body = patterns(args[0])
    elif kind == "Star":
        body = optional(args[0])
    elif kind == "Mapping":
        return f"MatchPattern::Mapping {{ keys:{patterns(args[0])},patterns:{patterns(args[1])},rest:{optional(args[2])} }}"
    elif kind == "Class":
        return f"MatchPattern::Class {{ path:{strings(args[0])},positional:{patterns(args[1])},keyword_names:{strings(args[2])},keyword_patterns:{patterns(args[3])} }}"
    elif kind == "As":
        child = "None" if args[0] is None else f"Some(Box::new({pattern(args[0])}))"
        return f"MatchPattern::As {{ pattern:{child},name:{optional(args[1])} }}"
    else:
        raise ValueError(f"unknown pattern {kind}")
    return f"MatchPattern::{kind}({body})"


def operation(instruction):
    name, args = instruction.op, instruction.args
    if name == "Const":
        body = constant(args[0])
    elif name == "Match":
        body = pattern(args[0])
    elif name == "Call":
        return f"Op::Call {{ pos:{args[0]},keywords:{strings(args[1])} }}"
    elif name == "MakeFunction":
        return f"Op::MakeFunction {{ code:{args[0]},defaults:{args[1]},kwdefaults:{strings(args[2])} }}"
    elif name == "MakeTypeParam":
        return f"Op::MakeTypeParam {{ name:{string(args[0])},kind:{string(args[1])} }}"
    elif name == "MakeTypeAlias":
        return f"Op::MakeTypeAlias {{ name:{string(args[0])} }}"
    elif name == "MakeClass":
        return f"Op::MakeClass {{ name:{string(args[0])},code:{args[1]},bases:{args[2]},keywords:{strings(args[3])} }}"
    elif name == "MakeClassEx":
        return f"Op::MakeClassEx {{ name:{string(args[0])},code:{args[1]} }}"
    elif name == "Import":
        return f"Op::Import {{ module:{string(args[0])},names:{strings(args[1])},level:{args[2]} }}"
    elif name == "FormatValue":
        return f"Op::FormatValue {{ conversion:{args[0]},spec:{str(args[1]).lower()} }}"
    elif name == "MakeInterpolation":
        return f"Op::MakeInterpolation {{ expression:{optional(args[0])},conversion:{args[1]},spec:{str(args[2]).lower()} }}"
    elif name == "UnpackEx":
        return f"Op::UnpackEx {{ before:{args[0]},after:{args[1]} }}"
    elif name == "CallEx":
        return f"Op::CallEx {{ kwargs:{str(args[0]).lower()} }}"
    elif args:
        body = ",".join(string(arg) if isinstance(arg, str) else str(arg).lower() for arg in args)
    else:
        return f"Op::{name}"
    return f"Op::{name}({body})"


def generate(program: Program, integer="i64", *, include_dynamic=True, native_leaves=False):
    bits = {"i64": 64, "i128": 128, "bigint": 0}[integer]
    prefix = "// Generated by py2fastrust. Runtime: MIT; see the notice below.\n"
    prefix += "#![allow(dead_code, unused_imports, unused_variables, unused_mut)]\n"
    prefix += f"const INT_BITS: u32 = {bits};\n"
    notice = files("py2fastrust").joinpath("runtime", "NOTICE.txt").read_text(encoding="utf-8")
    prefix += "/*\n" + notice + "\n*/\n"
    # Generated code can contain PSF-licensed standard-library algorithms.
    python_license = files("py2fastrust").joinpath("stdlib", "PYTHON_LICENSE.txt").read_text(encoding="utf-8")
    prefix += "\n".join("// " + line for line in python_license.splitlines()) + "\n"
    unicode_license = files("py2fastrust").joinpath("stdlib", "UNICODE_LICENSE.txt").read_text(encoding="utf-8")
    prefix += "\n".join("// " + line for line in unicode_license.splitlines()) + "\n"
    parts = [prefix]
    dynamic_components = {
        "dynamic.rs", "cst_lower.rs", "peg.rs", "peg_tables.rs", "peg_tokenizer.rs",
        "unicode_names.rs", "unicode_names_tables.rs",
    }
    for name in ("stdio.rs", "streaming_io.rs", "integer.rs", "complex.rs", "frozenset.rs", "vm.rs", "identity.rs", "keywords.rs", "protocol_calls.rs", "comprehensions.rs", "dynamic.rs", "cst_lower.rs", "patterns.rs", "math.rs", "itertools.rs", "builtin_instances.rs", "native_attributes.rs", "implicit_slots.rs", "operand_slots.rs", "text.rs", "traceback.rs", "range.rs", "codec.rs", "execution.rs", "builtin_hooks.rs", "namespace.rs", "globals.rs", "dict_views.rs", "collections.rs", "generic_alias.rs", "peg.rs", "peg_tables.rs", "peg_tokenizer.rs", "normalization.rs", "normalization_tables.rs", "unicode_names.rs", "unicode_names_tables.rs", "type_parameters.rs", "templates.rs", "exception_groups.rs"):
        if not include_dynamic and name in dynamic_components:
            continue
        parts.append(files("py2fastrust").joinpath("runtime", name).read_text(encoding="utf-8"))
    if not include_dynamic:
        parts.append(files("py2fastrust").joinpath("runtime", "dynamic_unreachable.rs").read_text(encoding="utf-8"))
    from .native_leaf import generate_native_leaves
    parts.append(generate_native_leaves(program, integer, enabled=native_leaves))
    parts.append("\nfn main() {\nlet codes = vec![\n")
    source_map = []
    for code_id, code in enumerate(program.codes):
        p = code.params
        parts.append(f"Code {{ name:{string(code.name)},qualname:{string(code.qualname if code.qualname is not None else code.name)},filename:{string(code.filename)},kind:ScopeKind::{code.kind},"
                     f"locals:{strings(code.locals)},comp_locals:{strings(code.comp_locals)},globals:{strings(code.globals)},nonlocals:{strings(code.nonlocals)},frees:{strings(code.frees)},"
                     f"params:Params {{ posonly:{p.posonly},positional:{strings(p.positional)},kwonly:{strings(p.kwonly)},"
                     f"vararg:{optional(p.vararg)},kwarg:{optional(p.kwarg)} }},"
                     f"is_generator:{str(code.is_generator).lower()},future_flags:{code.future_flags},docstring:{optional(code.docstring)},ops:vec![\n")
        for index, instruction in enumerate(code.ops):
            parts.append(f"Instr {{ op:{operation(instruction)},line:{instruction.line},column:{instruction.column} }},\n")
            source_map.append(SourceLocation(code_id, index, code.filename, instruction.line, instruction.column))
        parts.append("] },\n")
    parts.append("];\nlet modules = vec![" + ",".join(f"({string(name)},{index})" for name, index in program.modules) + "];\n")
    parts.append("let mut runtime = Runtime::new(codes, modules);\n"
                 "if let Err(error) = runtime.run() { runtime.finish(); "
                 "if runtime.exception_has_native_class(&error, \"SystemExit\") { let status = runtime.system_exit_status(&error); std::process::exit(status); } "
                 "runtime.report_exception(&error); std::process::exit(1); }\nruntime.finish();\n}\n")
    return "\n".join(parts), tuple(source_map)
