"""Deterministic output metadata, license text, and inert original source."""

import hashlib
from importlib.resources import files


PROJECT_URL = "https://github.com/harurunrunrun/py2fastrust"


def _comments(text):
    # Every physical line is independently commented. In particular, Python
    # imports and Rust-looking /* */ text can never become generated code.
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join("// " + line if line else "//" for line in lines)


def add_header(rust, source, options, backend):
    text = files("py2fastrust").joinpath("licenses", options.license + ".txt").read_text(encoding="utf-8")
    metadata = (
        f"LICENSE: {options.license}\n\n"
        f"This code is generated by the Python to Rust Transpiler ({PROJECT_URL}).\n"
        "Transpilation does not use generative AI.\n"
        f"Integer mode: {options.integer}.\n"
        f"String mode: {options.string_mode}.\n"
        f"Original source SHA-256: {hashlib.sha256(source.encode('utf-8')).hexdigest()}\n\n"
        "If the original Python source specifies a license, that license takes precedence.\n"
        f"Otherwise, the license for the translated program logic is {options.license}.\n"
        "Third-party notices follow only when their code or data is included.\n\n"
        f"{text.rstrip()}\n\n"
        "Original Python source (before import expansion):\n"
    )
    return _comments(metadata) + "\n//\n" + _comments(source) + "\n//\n\n" + rust
