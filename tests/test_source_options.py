"""Source directives, complete license headers, and inert source provenance."""

from importlib.resources import files
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

from py2fastrust import TranspileOptions, transpile
from py2fastrust.provenance import PROJECT_URL
from py2fastrust.settings import source_directives


class SourceOptionsTests(unittest.TestCase):
    def test_source_options_override_api_and_keep_source_locations(self):
        source = '#!/usr/bin/env python3\n# coding: utf-8\n\n# py2fastrust: --int i128 --license Unlicense --no-optimize\nprint(2**70)\n'
        result = transpile(source, TranspileOptions(integer="i64", license="MIT", filename="solution.py"))
        self.assertTrue(result.success, result.diagnostics)
        self.assertEqual(result.backend, "vm")
        self.assertTrue(result.rust_source.startswith("// LICENSE: Unlicense\n//\n"))
        self.assertIn("const INT_BITS: u32 = 128;", result.rust_source)
        self.assertTrue(any(location.line == 5 and location.filename == "solution.py" for location in result.source_map))
        result = transpile('# py2fastrust: --optimize\nprint(2)\n', TranspileOptions(optimize=False))
        self.assertEqual(result.backend, "native")

    def test_only_initial_comments_are_options_and_last_value_wins(self):
        source = '# py2fastrust: --int i128\n# ordinary comment\n# py2fastrust: --int bigint --license cc0\npass\n# py2fastrust: --int invalid\n'
        values = source_directives(source, "input.py")
        self.assertEqual(values, {"integer": "bigint", "license": "CC0-1.0"})
        self.assertEqual(source_directives('"""\n# py2fastrust: --int invalid\n"""\n', "input.py"), {})
        self.assertTrue(transpile('print(1)\n# py2fastrust: --int invalid\n').success)
        self.assertEqual(source_directives('# pytors: --int i128 --license MIT\nprint(1)', 'input.py'),
                         {'integer': 'i128', 'license': 'MIT'})

    def test_cli_name_and_license_catalog(self):
        result = subprocess.run([sys.executable, '-m', 'py2fastrust', '--help'], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(result.stdout.startswith('usage: pytors '))
        result = subprocess.run([sys.executable, '-m', 'py2fastrust', '--list-licenses'], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        from py2fastrust.settings import LICENSES
        self.assertEqual(result.stdout.splitlines(), list(LICENSES))
        self.assertTrue({'CC0-1.0', 'Unlicense', 'MIT'} <= set(LICENSES))

    def test_malformed_directives_are_located_diagnostics(self):
        for directive in ('--int i32', '--license unknown', '--int', '--help', '--version',
                          'other.py', '--unknown value', '--license "unterminated'):
            with self.subTest(directive=directive):
                result = transpile('# comment\n# py2fastrust: ' + directive + '\nprint(1)\n', TranspileOptions(filename="bad.py"))
                self.assertFalse(result.success)
                diagnostic = result.diagnostics[0]
                self.assertEqual((diagnostic.filename, diagnostic.line, diagnostic.column, diagnostic.code),
                                 ("bad.py", 2, 1, "E004"))
        result = transpile('print(1)', TranspileOptions(license="unknown"))
        self.assertFalse(result.success)
        self.assertEqual(result.diagnostics[0].code, "E004")

    def test_all_license_texts_and_original_source_are_complete(self):
        source = 'import sys\nprint("/* nested */ // comment \\N{SNOWMAN}")\n'
        for license in ("CC0-1.0", "Unlicense", "MIT"):
            with self.subTest(license=license):
                result = transpile(source, TranspileOptions(license=license))
                self.assertTrue(result.success, result.diagnostics)
                rust = result.rust_source
                self.assertTrue(rust.startswith(f"// LICENSE: {license}\n"))
                self.assertIn(PROJECT_URL, rust)
                self.assertIn("// Transpilation does not use generative AI.\n", rust)
                self.assertTrue("// If the original Python source specifies a license, that license takes precedence.\n" in rust)
                text = files("py2fastrust").joinpath("licenses", license + ".txt").read_text()
                for line in text.splitlines():
                    self.assertIn("// " + line + "\n" if line else "//\n", rust)
                before, generated = rust.split("// Generated by py2fastrust", 1)
                for line in source.splitlines():
                    self.assertIn("// " + line + "\n", before)
                self.assertNotIn("// import sys\n", generated)
                runtime_notice = files("py2fastrust").joinpath("runtime", "NOTICE.txt").read_text()
                self.assertTrue(runtime_notice in generated, "runtime license notice must remain intact")
                self.assertTrue("PYTHON SOFTWARE FOUNDATION LICENSE" in generated)
        self.assertTrue(transpile('print(1)').rust_source.startswith('// LICENSE: CC0-1.0\n'))

    def test_source_module_paths_and_includes_replace_command_line_lists(self):
        with tempfile.TemporaryDirectory(prefix="py2fastrust-directive-modules-") as directory:
            root = Path(directory)
            library = root / "local library"
            library.mkdir()
            (library / "included.py").write_text('value=17\n')
            source = '# py2fastrust: --module-path "local library" --include-module included\nexec("import included\\nprint(included.value)")\n'
            result = transpile(source, TranspileOptions(filename=str(root / "main.py"),
                               module_paths=(root / "wrong",), include_modules=("missing",)))
            self.assertTrue(result.success, result.diagnostics)
            self.assertIn('included.py', result.rust_source)

    def test_original_source_preserves_non_newline_unicode_separators(self):
        source = '# ordinary\x85comment\vwith\u2028separators\nprint("a\u2028b")\n'
        result = transpile(source)
        self.assertTrue(result.success, result.diagnostics)
        header = result.rust_source.split('// Generated by py2fastrust', 1)[0]
        for line in source.split('\n'):
            self.assertTrue('// ' + line + '\n' in header if line else '//\n' in header)

    def test_cli_source_options_override_flags_and_output(self):
        with tempfile.TemporaryDirectory(prefix="py2fastrust-directive-cli-") as directory:
            root = Path(directory)
            source = root / "main.py"
            source.write_text('# py2fastrust: --int i128 --license Unlicense -o "from source.rs"\nprint(2**70)\n')
            output = root / "from flags.rs"
            output.write_text("keep")
            result = subprocess.run([sys.executable, '-m', 'py2fastrust', str(source), '-o', str(output),
                                     '--int', 'i64', '--license', 'MIT'], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(output.read_text(), 'keep')
            rust = (root / "from source.rs").read_text()
            self.assertTrue(rust.startswith('// LICENSE: Unlicense\n'))
            self.assertIn('const INT_BITS: u32 = 128;', rust)
            source.write_text('# py2fastrust: --check\nprint(1)\n')
            result = subprocess.run([sys.executable, '-m', 'py2fastrust', str(source), '-o', str(output)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(output.read_text(), 'keep')
            source.write_text('# py2fastrust: --license invalid\nprint(1)\n')
            result = subprocess.run([sys.executable, '-m', 'py2fastrust', str(source), '-o', str(output)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 2)
            self.assertIn('main.py:1:1: E004:', result.stderr)
            self.assertEqual(output.read_text(), 'keep')

    @unittest.skipUnless(shutil.which('rustc'), 'rustc is required')
    def test_headers_compile_for_both_backends_and_every_license(self):
        with tempfile.TemporaryDirectory(prefix="py2fastrust-header-compile-") as directory:
            root = Path(directory)
            for optimize in (True, False):
                for license in ('CC0-1.0', 'Unlicense', 'MIT'):
                    source = ('# py2fastrust: --int i128\n'
                              '# /* */ fn main() {} #![allow(anything)]\n'
                              '# Unicode separators remain text: \x85\v\u2028\n'
                              'n = 2**70\nprint(n)\n')
                    result = transpile(source, TranspileOptions(optimize=optimize, license=license))
                    self.assertTrue(result.success, result.diagnostics)
                    rust = root / 'main.rs'
                    rust.write_text(result.rust_source)
                    compiled = subprocess.run(['rustc', '--edition=2021', str(rust), '-o', str(root / 'main')], capture_output=True, text=True, timeout=120)
                    self.assertEqual(compiled.returncode, 0, compiled.stderr)
                    actual = subprocess.run([str(root / 'main')], capture_output=True, text=True, timeout=10)
                    self.assertEqual(actual.returncode, 0, actual.stderr)
                    self.assertEqual(actual.stdout, str(2**70) + '\n')
