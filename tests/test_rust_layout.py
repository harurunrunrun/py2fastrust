"""Output layout must preserve executable literals and complete license text."""

import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from py2fastrust import TranspileOptions, transpile
from py2fastrust.rust_layout import compact_blank_lines, strip_comments
from py2fastrust.rust_pruning import _lex


class RustLayoutTests(unittest.TestCase):
    def test_comment_stripping_keeps_literals_and_separates_tokens(self):
        source = '''// implementation explanation
/// documentation
fn/* another explanation */main() {
    let text=r###"// literal
/* literal */"###;
    let ordinary="// and /* remain literal */";
    /* nested /* comment */ also removed */
    println!("{text}{ordinary}");
}
'''
        before, _comments, _pairs = _lex(source)
        result = strip_comments(source)
        after, comments, _pairs = _lex(result)
        self.assertFalse(comments)
        self.assertEqual([(token.kind, token.text) for token in before],
                         [(token.kind, token.text) for token in after])
        self.assertIn('fn main()', result)

    def test_only_blank_lines_outside_literals_and_comments_are_compacted(self):
        source = '''// generated

 

/* license


must be unchanged */


fn main() {
    let raw = r###"first


last"###;


    let normal = "first


last";
    assert_eq!(raw, normal);
    print!("{}", raw);
}
'''
        compact = compact_blank_lines(source)
        self.assertLess(len(compact), len(source))
        self.assertEqual(compact_blank_lines(compact), compact)
        before_tokens, before_comments, _ = _lex(source)
        after_tokens, after_comments, _ = _lex(compact)
        self.assertEqual([(token.kind, token.text) for token in before_tokens],
                         [(token.kind, token.text) for token in after_tokens])
        self.assertEqual([source[a:b] for a, b, _ in before_comments],
                         [compact[a:b] for a, b, _ in after_comments])
        if shutil.which("rustc"):
            with tempfile.TemporaryDirectory(prefix="pytors-layout-") as temporary:
                root = Path(temporary)
                (root / "main.rs").write_text(compact)
                compiled = subprocess.run(["rustc", "--edition=2021", str(root / "main.rs"),
                                           "-o", str(root / "main")], capture_output=True, text=True)
                self.assertEqual(compiled.returncode, 0, compiled.stderr)
                result = subprocess.run([str(root / "main")], capture_output=True, text=True)
                self.assertEqual((result.returncode, result.stdout), (0, "first\n\n\nlast"))

    def test_all_integer_modes_keep_original_source_and_compact_pruning_gaps(self):
        source = '# ordinary source comment\n\n\nprint("first\\n\\nlast")\n'
        for integer in ("i64", "i128", "bigint"):
            with self.subTest(integer=integer):
                result = transpile(source, TranspileOptions(integer=integer))
                self.assertTrue(result.success, result.diagnostics)
                header, code = result.rust_source.split("\n#![", 1)
                self.assertIn('// # ordinary source comment\n//\n//\n// print(', header)
                self.assertNotRegex(code, r"\n[ \t]*\n[ \t]*\n")
                self.assertNotIn("Copyright (c) 2026 py2fastrust contributors", result.rust_source)

    def test_generated_implementation_has_no_explanatory_comments(self):
        cases = ('s=input()\nprint(s[0],len(s))\n',
                 'class Text:\n def __init__(self,s):self.s=s\nt=Text(input())\nprint(t.s)\n')
        for integer in ("i64", "i128", "bigint"):
            for optimize in (False, True):
                for source in cases:
                    with self.subTest(integer=integer, optimize=optimize, source=source):
                        result = transpile(source, TranspileOptions(integer=integer, optimize=optimize))
                        self.assertTrue(result.success, result.diagnostics)
                        _header, code = result.rust_source.split("\n#![", 1)
                        code = "#![" + code
                        # No-optimize retains unused third-party helpers/notices.
                        implementation = code.split("// CPython-derived native_float_divmod:", 1)[0]
                        implementation = implementation.split("// UNICODE LICENSE V3", 1)[0]
                        _tokens, comments, _pairs = _lex(implementation)
                        self.assertFalse(comments, [implementation[a:b] for a,b,_ in comments])
                        self.assertNotIn("// Generated by py2fastrust", result.rust_source)


if __name__ == "__main__":
    unittest.main()
